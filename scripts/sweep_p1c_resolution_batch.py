#!/usr/bin/env python3
"""Sweep training resolution against batch size on the video blob.

CALIBRATION-006 showed the loader contributes ~0.2% of wall time and the
accelerator holds under 5% of its memory, so both resolution and batch size
became free parameters rather than constraints. They interact -- a bigger batch
changes what a resolution costs -- so measuring them separately would be
wasteful and slightly wrong. This runs the grid.

**Why one process, not one pod per config.** Staging the 84.3 GiB blob costs
~150 s and verifying its SHA-256 costs ~112 s. The verification is memoised per
*process* (`data.video_blob._VERIFIED_BLOBS`), so running the grid inside a
single interpreter hashes once instead of once per configuration -- about nine
minutes saved on a six-point grid, and the saving grows with the grid.

**Why the grid is ordered cheapest-first.** A configuration that exhausts
device memory is a legitimate and interesting outcome, not a crash to avoid:
it marks the edge of what one `mig-1g.18gb` slice can hold. Ordering by
ascending cost means any such failure lands at the end, after every cheaper
point has already been measured and recorded.

Each point gets its own registered config file with its own digest, because
the artifact each run emits references the config that produced it.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import torch  # noqa: E402

from scripts.calibrate_p1c_frame_loader import main as calibrate_main  # noqa: E402

BASE_CONFIG = REPO_ROOT / "configs/experiments/p1c/P1C-VIDEO-PRECISION-CALIBRATION-007-BF16.yaml"
SWEEP_DIR = REPO_ROOT / "configs/experiments/p1c/sweep-009"
SWEEP_ID = "P1C-VIDEO-SWEEP-009"

# Ascending cost: activation memory scales with batch x pixels, so this is
# also ascending device-memory pressure.
DEFAULT_RESOLUTIONS = ("64", "112", "224")
DEFAULT_BATCHES = (64, 256)

# The corpus is natively 240x320 (H x W), which is neither square nor smaller
# than 224 -- it is 1.53x the pixels. Geometry is therefore carried as an
# explicit (height, width) pair rather than one number.
NATIVE_HEIGHT, NATIVE_WIDTH = 240, 320


def parse_geometry(value: str | int) -> tuple[int, int]:
    """Accept `224` (square) or `240x320` (explicit height x width).

    `native` resolves to the corpus geometry. Square shorthand is kept because
    every point measured before 2026-08-25 used it and the ids embed it.
    """
    text = str(value).strip().lower()
    if text == "native":
        return NATIVE_HEIGHT, NATIVE_WIDTH
    if "x" in text:
        height, width = text.split("x", 1)
        return int(height), int(width)
    side = int(text)
    return side, side


def geometry_label(height: int, width: int) -> str:
    """`224` for square, `240x320` otherwise -- keeps existing ids stable."""
    return str(height) if height == width else f"{height}x{width}"


def grid(resolutions, batches) -> list[tuple[int, int, int]]:
    """Points as (height, width, batch), ordered cheapest first."""
    points = [(*parse_geometry(r), b) for r in resolutions for b in batches]
    return sorted(points, key=lambda point: point[0] * point[1] * point[2])


def write_config(height: int, width: int, batch: int, *, base_text: str, output_dir: Path) -> Path:
    """Materialise one grid point as a registered config."""
    experiment_id = f"{SWEEP_ID}-R{geometry_label(height, width)}-B{batch}"
    text = base_text
    text = text.replace("  id: P1C-VIDEO-PRECISION-CALIBRATION-007-BF16", f"  id: {experiment_id}")
    text = text.replace(
        "  parent_id: P1C-VIDEO-GAP-CALIBRATION-006",
        "  parent_id: P1C-VIDEO-PRECISION-CALIBRATION-007-BF16",
    )
    text = text.replace("    resize_height: 64", f"    resize_height: {height}")
    text = text.replace("    resize_width: 64", f"    resize_width: {width}")
    text = text.replace("    batch_size: 64", f"    batch_size: {batch}")
    header = (
        f"# {experiment_id}: generated grid point, {height}x{width} at batch {batch}.\n"
        f"#\n"
        f"# GENERATED by scripts/sweep_p1c_resolution_batch.py from\n"
        f"# {BASE_CONFIG.name}. Two fields differ from that parent:\n"
        f"# preprocessing.resize_height/width and training.batch_size. Precision is\n"
        f"# bfloat16 throughout the sweep, per the owner decision of 2026-08-25.\n"
        f"#\n"
        f"# This point is therefore NOT single-factor against its parent and cannot\n"
        f"# attribute a delta to resolution or batch size alone -- the grid as a whole\n"
        f"# is what separates them. Calibration only: throughput and memory, no\n"
        f"# accuracy, no model selection.\n"
    )
    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"{experiment_id}.yaml"
    path.write_text(header + text, encoding="utf-8")
    return path


def run_point_isolated(config_path: Path) -> dict[str, object]:
    """Run one point in its own interpreter.

    Costs a fresh 84.3 GiB blob verification per point (~112 s), because the
    verification memo lives in the process being discarded. Buys complete
    isolation: `persistent_workers=True` keeps six worker processes alive per
    loader, and in-process those accumulate across points until the pool
    destabilises -- measured 2026-08-25, where points 1-2 passed and every
    point after failed progressively sooner with workers aborting (K-18).
    """
    started = time.perf_counter()
    completed = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts/calibrate_p1c_frame_loader.py"),
         "--config", str(config_path)],
        cwd=REPO_ROOT, capture_output=True, text=True,
    )
    seconds = time.perf_counter() - started
    if completed.returncode == 0:
        return {"status": "COMPLETED", "exit_code": 0, "seconds": seconds}
    tail = (completed.stderr or completed.stdout or "").strip().splitlines()
    return {"status": "FAILED", "exit_code": completed.returncode, "seconds": seconds,
            "error": "\n".join(tail[-12:])[:1200]}


def run_point(config_path: Path) -> dict[str, object]:
    """Run one point, converting a device-memory failure into a recorded result."""
    started = time.perf_counter()
    try:
        code = calibrate_main(["--config", str(config_path)])
        return {"status": "COMPLETED" if code == 0 else "FAILED",
                "exit_code": code, "seconds": time.perf_counter() - started}
    except torch.cuda.OutOfMemoryError as exc:
        # The edge of the slice: a real measurement, not an accident.
        return {"status": "DEVICE_OOM", "error": str(exc)[:300],
                "seconds": time.perf_counter() - started}
    except Exception as exc:  # noqa: BLE001 - one bad point must not end the sweep
        return {"status": "ERROR", "error": f"{type(exc).__name__}: {exc}"[:300],
                "seconds": time.perf_counter() - started}
    finally:
        # Release the failed point's allocations before the next one starts,
        # or an OOM here would cascade into every later point.
        if torch.cuda.is_available():
            torch.cuda.empty_cache()
            torch.cuda.reset_peak_memory_stats()


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--resolutions", nargs="+", default=list(DEFAULT_RESOLUTIONS),
                        help="square side (224), explicit geometry (240x320), or 'native'")
    parser.add_argument("--batches", type=int, nargs="+", default=list(DEFAULT_BATCHES))
    parser.add_argument("--config-dir", type=Path, default=SWEEP_DIR)
    parser.add_argument("--isolate", action="store_true",
                        help="run each point in its own interpreter (slower, but immune to "
                             "persistent-worker accumulation across points)")
    parser.add_argument("--summary", type=Path,
                        default=REPO_ROOT / "results/p1c/p1c-video-sweep-009-summary.json")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    base_text = BASE_CONFIG.read_text(encoding="utf-8")
    points = grid(args.resolutions, args.batches)
    print(f"sweep: {len(points)} points, cheapest first: {points}", flush=True)

    results = []
    for index, (height, width, batch) in enumerate(points, start=1):
        config_path = write_config(height, width, batch, base_text=base_text,
                                   output_dir=args.config_dir)
        print(f"\n===== [{index}/{len(points)}] {height}x{width} batch {batch} =====", flush=True)
        outcome = run_point_isolated(config_path) if args.isolate else run_point(config_path)
        outcome.update(resize_height=height, resize_width=width, batch_size=batch,
                       config=config_path.name)
        results.append(outcome)
        print(f"----- {outcome['status']} in {outcome['seconds']:.1f}s", flush=True)

    args.summary.parent.mkdir(parents=True, exist_ok=True)
    args.summary.write_text(json.dumps(
        {"sweep_id": SWEEP_ID, "base_config": BASE_CONFIG.name, "points": results},
        indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"\nsweep summary: {args.summary}", flush=True)

    completed = sum(1 for r in results if r["status"] == "COMPLETED")
    print(f"{completed}/{len(results)} points completed")
    # A device-memory refusal is a result, not a sweep failure.
    return 0 if completed else 1


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
